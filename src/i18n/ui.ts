export type UIKey = keyof (typeof ui)["en"];

export function t(lang: Lang, key: UIKey, vars: Record<string, string | number> = {}): string {
  let s: string = (ui[lang] as Record<string, string>)[key] ?? ui.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

/** Build a localized path. English lives at the root, others under /ar/ and /fr/. */
export function lp(lang: Lang, path = "/"): string {
  const clean = path.startsWith("/") ? path : `/${path}`;
  return lang === DEFAULT_LOCALE ? clean : `/${lang}${clean}`;
}

